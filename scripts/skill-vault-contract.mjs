// Only selection identities/allowed axes, never prices or compiled battle effects.
// On catalog changes, generate a NEW migration replacing the contract function.
import { createASkillCatalog } from '../js/aSkillCatalog.js';
import { createBSkillCatalog } from '../js/bSkillCatalog.js';
import { createCSkillCatalog } from '../js/cSkillCatalog.js';
import { createCSkillRules } from '../js/cSkillRules.js';
import { D_SKILL_OPTIONS } from '../js/dSkillCatalog.js';
const object = (fields, optional = []) => ({ fields, optional });
export function skillVaultContract() {
  const catalogs = { A: createASkillCatalog(), B: createBSkillCatalog(), C: createCSkillCatalog() };
  const result = { A: [], B: [], C: [], D: D_SKILL_OPTIONS.map(o => o.id),
    maxA: catalogs.A.maxEffects, maxC: createCSkillRules().maxEffects,
    thresholds: catalogs.C.optionSets.hpThreshold.map(o => o.id) };
  for (const [type, catalog] of Object.entries(catalogs)) {
    for (const row of catalog.selectionEffects.flatMap(d => d.variants)) {
      const d = row.definition;
      const fields = { effectId: [row.effectId], targetId: [row.targetId] };
      if (row.statusId !== undefined) fields.statusId = [row.statusId];
      fields.options = object({ ...Object.fromEntries(Object.entries(row.fixedOptions).map(([k, v]) => [k, [v]])),
        ...Object.fromEntries(Object.entries(row.optionAxes).map(([k, v]) => [k, v.map(o => o.id)])) });
      if (type === 'B') Object.assign(fields, { type: ['event'], triggerId: [d.triggerId], conditionId: [d.conditionId] });
      const optional = [];
      if (type === 'A' || row.chanceEnabled) { fields.chanceOptionId = type === 'A' ? ['100'] : catalog.chanceOptions.map(o => o.id); optional.push('chanceOptionId'); }
      if (type === 'A' && d.exactFace != null) { fields.options.fields.diceAction = [String(d.exactFace)]; fields.options.optional.push('diceAction'); }
      const meta = type === 'A' ? { id: d.id, duplicate: !!d.allowDuplicate, face: d.exactFace ?? null,
        cancel: !!d.cancelsNormalAttack, conflict: !!d.conflictsWithAttackCancel }
        : type === 'C' ? { modes: d.modes } : {};
      result[type].push({ schema: object(fields, optional), ...meta });
    }
    // Legacy selections are kept verbatim too; loading never substitutes an effect.
    for (const d of type === 'B' ? catalog.events : catalog.effects) {
      const fields = { effectId: [type === 'B' ? d.effectId : d.id] }, optional = [];
      if (type === 'A') {
        if (d.requiresAmount) fields.amountOptionId = d.amountOptions.map(o => o.id);
        fields.chanceOptionId = ['100']; optional.push('chanceOptionId');
      } else {
        fields.options = object(Object.fromEntries(Object.entries(d.optionAxes).map(([k, set]) => [k, catalog.optionSets[set].map(o => o.id)])));
        if (type === 'B') Object.assign(fields, { type: ['event'], triggerId: [d.triggerId], conditionId: [d.conditionId] });
        else {
          if (!Object.keys(d.optionAxes).length) optional.push('options');
          if (d.chanceEnabled) { fields.chanceOptionId = catalog.chanceOptions.map(o => o.id); optional.push('chanceOptionId'); }
        }
      }
      result[type].push({ schema: object(fields, optional), ...(type === 'A' ? { id: d.id, duplicate: !!d.allowDuplicate,
        face: d.exactFace ?? null, cancel: !!d.cancelsNormalAttack, conflict: !!d.conflictsWithAttackCancel } : type === 'C' ? { modes: d.modes } : {}) });
    }
  }
  for (const d of catalogs.B.traits) result.B.push({ schema: object({ type: ['trait'], traitId: [d.id],
    options: object(Object.fromEntries(Object.entries(d.optionAxes).map(([k, set]) => [k, catalogs.B.optionSets[set].map(o => o.id)]))) }) });
  return result;
}
export function skillVaultContractSQL() {
  return `-- Generated by scripts/skill-vault-contract.mjs; update through a new migration.\ncreate or replace function diesduck_private.skill_vault_contract() returns jsonb\nlanguage sql immutable set search_path = '' as $contract$\nselect $json$${JSON.stringify(skillVaultContract())}$json$::jsonb;\n$contract$;\nrevoke all on function diesduck_private.skill_vault_contract() from public, anon, authenticated;\n`;
}
